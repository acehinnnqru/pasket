import AppKit
import UniformTypeIdentifiers

extension NSPasteboard.PasteboardType {
    static let gifImage = Self(UTType.gif.identifier)
}

enum ClipboardCapture {
    case text(String, ClipboardSource, Date)
    case image(Data, ClipboardSource, Date)
    case files([ClipboardFile], ClipboardSource, Date)
}

@MainActor
final class ClipboardMonitor {
    var onCapture: ((ClipboardCapture) -> Void)?
    var onNotice: ((String) -> Void)?
    var onAccessChange: ((Bool) -> Void)?
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var changeCount: Int
    private var isPaused = false
    private var accessDenied: Bool?
    private var lastExternalSource = ClipboardSource.unknown
    private var applicationObserver: NSObjectProtocol?

    init(pasteboard: NSPasteboard) {
        self.pasteboard = pasteboard
        changeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        checkpoint()
        reportAccess()
        updateSource(NSWorkspace.shared.frontmostApplication)
        applicationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] notification in
            MainActor.assumeIsolated {
                self?.updateSource(notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication)
            }
        }
        let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        if let applicationObserver { NSWorkspace.shared.notificationCenter.removeObserver(applicationObserver) }
        applicationObserver = nil
    }

    func setPaused(_ paused: Bool) {
        isPaused = paused
        checkpoint()
    }

    func checkpoint() { changeCount = pasteboard.changeCount }

    func poll() {
        reportAccess()
        let observedCount = pasteboard.changeCount
        guard observedCount != changeCount else { return }
        changeCount = observedCount
        guard !isPaused, accessDenied != true else { return }
        let excludedTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
            .map { NSPasteboard.PasteboardType($0) }
        guard !excludedTypes.contains(where: { pasteboard.types?.contains($0) == true }) else { return }

        updateSource(NSWorkspace.shared.frontmostApplication)
        let source = lastExternalSource
        let date = Date()
        let capture: ClipboardCapture
        if pasteboard.types?.contains(.fileURL) == true {
            guard let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
                  !urls.isEmpty else { return }
            guard urls.count <= 100 else {
                onNotice?("Files not saved: copy up to 100 files at a time.")
                return
            }
            capture = .files(urls.map(ClipboardFileAccess.capture), source, date)
        } else if let data = imageData() {
            guard data.count <= ClipboardLimits.imageBytes else {
                onNotice?("Image not saved: the limit is 20 MB.")
                return
            }
            capture = .image(data, source, date)
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty {
            // Count extended grapheme clusters without walking the rest of an oversized string.
            guard text.prefix(ClipboardLimits.textCharacters + 1).count <= ClipboardLimits.textCharacters else {
                onNotice?("Text not saved: the limit is 2,000 characters.")
                return
            }
            guard text.contains(where: { !$0.isWhitespace }) else { return }
            capture = .text(text, source, date)
        } else {
            return
        }
        // A writer may change the pasteboard while its representations are being read.
        guard pasteboard.changeCount == observedCount else { return }
        onCapture?(capture)
    }

    private func imageData() -> Data? {
        if pasteboard.types?.contains(.gifImage) == true,
           let data = pasteboard.data(forType: .gifImage), !data.isEmpty {
            return data
        }
        let types: [NSPasteboard.PasteboardType] = [.png, .tiff, .init(UTType.jpeg.identifier)]
        guard let type = pasteboard.availableType(from: types) else { return nil }
        return pasteboard.data(forType: type)
    }

    private func updateSource(_ application: NSRunningApplication?) {
        guard let application, application.processIdentifier != ProcessInfo.processInfo.processIdentifier else { return }
        lastExternalSource = ClipboardSource(name: application.localizedName ?? "Unknown App", bundleIdentifier: application.bundleIdentifier)
    }

    private func reportAccess() {
        let denied = pasteboard.accessBehavior == .alwaysDeny
        if accessDenied != denied {
            accessDenied = denied
            onAccessChange?(denied)
        }
    }
}
